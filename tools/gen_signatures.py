"""Builds the signature table the plugin checks itself against at startup.

Every address in this port was read out of one executable. If a player's game is
not that executable - a different build, a different patch, anything - those
addresses point at something else, and a plugin that goes ahead anyway does not
fail cleanly: it corrupts whatever happens to be there and the game dies later,
somewhere unrelated, differently on every machine.

So the addresses are recorded here with the bytes that are supposed to be at
them, and the plugin compares before it touches anything. What it does about a
mismatch depends on where the address lives:

  * code (.text)   - the bytes are fixed in the file and must match exactly. A
                     mismatch means this is not the executable the port was
                     written against, and nothing is safe.
  * tables (.rdata)- vtables. Their contents are fixed in the file too, but
                     another plugin hooking the same slot first is normal and
                     expected, so a mismatch there is reported, not fatal.
  * variables      - anything the game writes to at runtime cannot be compared
                     against the file at all. Only the section is checked.

    py -3.11 tools/gen_signatures.py [output header]   (TESV_EXE = path to TESV.exe 1.9.32.0.8)
"""
import os
import re
import struct
import sys

EXE = os.environ.get('TESV_EXE', r'C:\Games\The Elder Scrolls V - Skyrim - Legendary Edition\TESV.exe')
SRC = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SRC, 'Signatures.h')
NBYTES = 24

d = open(EXE, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3C)[0]
n_sections = struct.unpack_from('<H', d, pe + 6)[0]
opt_size = struct.unpack_from('<H', d, pe + 20)[0]
image_base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
sections = []
off = pe + 24 + opt_size
for _ in range(n_sections):
    name = d[off:off + 8].rstrip(b'\0').decode('latin1')
    vsize, va, rawsize, raw = struct.unpack_from('<IIII', d, off + 8)
    sections.append((name, va, vsize, raw, rawsize))
    off += 40


def locate(va):
    rva = va - image_base
    for name, sva, vsize, raw, rawsize in sections:
        if sva <= rva < sva + max(vsize, rawsize):
            file_off = raw + (rva - sva)
            initialised = (rva - sva) < rawsize
            return name, (file_off if initialised else None)
    return None, None


# Constants that look like addresses but are masks or flags.
NOT_ADDRESSES = {0x00FFFFFF, 0x00000800, 0x00018902, 0x00008802, 0x00000411, 0x00010000, 0x00400000}

# --- every address the port names, with whatever it is called ---------------
found = {}
for fn in sorted(os.listdir(SRC)):
    if not fn.endswith(('.cpp', '.h')) or fn == 'Signatures.h':
        continue
    for line in open(os.path.join(SRC, fn), encoding='utf-8', errors='replace'):
        for m in re.finditer(r'0x0[01][0-9A-Fa-f]{6}', line):
            va = int(m.group(0), 16)
            if va in NOT_ADDRESSES or va in found:
                continue
            label = re.search(r'([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\(', line)
            if not label:
                label = re.search(r'\b(k[A-Z][A-Za-z0-9_]*)\b', line)
            found[va] = (label.group(1) if label else fn.split('.')[0], fn)

rows = []
for va in sorted(found):
    label, fn = found[va]
    sec, file_off = locate(va)
    if sec is None:
        print('  SKIPPED 0x%08X (%s): outside every section' % (va, label))
        continue
    if file_off is None:
        kind, sig = 'kVariable', b''
    elif sec == '.text':
        kind, sig = 'kCode', d[file_off:file_off + NBYTES]
    elif sec in ('.rdata', '.data'):
        kind, sig = ('kTable' if sec == '.rdata' else 'kVariable'), \
                    (d[file_off:file_off + NBYTES] if sec == '.rdata' else b'')
    else:
        kind, sig = 'kVariable', b''
    rows.append((va, label, fn, sec, kind, sig))

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('''// Signatures.h - what is supposed to be at every address this port uses.
//
// GENERATED by scripts/gen_signatures.py (QuickLoot IE LE) from TESV.exe 1.9.32.0.8.
// Do not edit by hand: re-run the generator.
//
// See Verify.cpp for what is done with it, and gen_signatures.py (QuickLoot IE LE) for
// why each kind is treated differently.

#pragma once

#include "skse/skse_version.h"

namespace Signatures
{
\tenum Kind
\t{
\t\tkCode,       // a function: the bytes are fixed and must match
\t\tkTable,      // a vtable: fixed too, but another plugin may hook it first
\t\tkVariable,   // written by the game at runtime: only the address is checked
\t};

\tstruct Site
\t{
\t\tunsigned long\taddress;
\t\tconst char *\tname;
\t\tconst char *\twhere;
\t\tKind\t\t\tkind;
\t\tunsigned char\tbytes[%d];
\t\tunsigned char\tlength;
\t};

\tstatic const Site kSites[] =
\t{
''' % NBYTES)
    for va, label, fn, sec, kind, sig in rows:
        b = ', '.join('0x%02X' % c for c in sig) if sig else ''
        pad = ', '.join(['0x00'] * (NBYTES - len(sig)))
        allb = (b + (', ' if b and pad else '') + pad)
        f.write('\t\t{ 0x%08X, "%s", "%s", %s, { %s }, %d },\n'
                % (va, label, fn, kind, allb, len(sig)))
    f.write('\t};\n\n\tenum { kSiteCount = %d };\n}\n' % len(rows))

kinds = {}
for _, _, _, sec, kind, sig in rows:
    kinds[kind] = kinds.get(kind, 0) + 1
print('%s: %d sites' % (OUT, len(rows)))
for k, v in sorted(kinds.items()):
    print('   %-10s %d' % (k, v))
